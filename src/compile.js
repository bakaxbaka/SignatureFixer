import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";

/** Canonical assembly order. Tier arrays are subsequences of this list. */
export const ORDER = [
  "envelope",
  "kernel",
  "scope",
  "livecheck",
  "phraseban",
  "loop",
  "done",
  "never",
  "lang",
  "idem",
];

/** @type {Record<"nano" | "core" | "full", string[]>} */
export const TIERS = {
  nano: ["kernel", "phraseban"],
  core: ["envelope", "kernel", "scope", "livecheck", "phraseban", "done", "never", "idem"],
  full: ORDER.slice(),
};

/** @type {Record<string, { noun: string | null, unit: string }>} */
export const PROFILES = {
  generic: { noun: null, unit: "iteration" },
  coding: { noun: "coding agent", unit: "iteration" },
  chat: { noun: "assistant", unit: "turn" },
  browser: { noun: "browser agent", unit: "iteration" },
  cli: { noun: "CLI agent", unit: "iteration" },
};

const KNOWN = new Set(ORDER);

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "..");

/**
 * Resolve `rel` against `root` and refuse anything that leaves `root`,
 * including a symlink whose real path does.
 * @param {string} root
 * @param {string} rel
 */
export function resolveInside(root, rel) {
  const rootAbs = path.resolve(root);
  const abs = path.resolve(rootAbs, rel);
  if (!contained(rootAbs, abs)) throw new Error("path escapes root");
  if (fs.existsSync(abs)) {
    const realRoot = fs.realpathSync(rootAbs);
    const realAbs = fs.realpathSync(abs);
    if (!contained(realRoot, realAbs)) throw new Error("path escapes root");
    return realAbs;
  }
  return abs;
}

/**
 * @param {string} rootAbs
 * @param {string} abs
 */
function contained(rootAbs, abs) {
  const relTo = path.relative(rootAbs, abs);
  if (relTo === ".." || relTo.startsWith(".." + path.sep) || path.isAbsolute(relTo)) {
    return false;
  }
  return true;
}

/**
 * @param {string} [root]
 * @returns {Record<string, string>}
 */
export function loadPayloads(root = ROOT) {
  /** @type {Record<string, string>} */
  const map = Object.create(null);
  for (const id of ORDER) {
    const abs = resolveInside(root, path.join("payloads", `${id}.txt`));
    map[id] = fs.readFileSync(abs, "utf8");
  }
  return map;
}

/**
 * @param {unknown} input
 */
function readInput(input) {
  if (!input || typeof input !== "object") {
    return { tier: undefined, modules: /** @type {unknown} */ ([]), profile: undefined };
  }
  const rec = /** @type {Record<string, unknown>} */ (input);
  return {
    tier: typeof rec.tier === "string" ? rec.tier : undefined,
    modules: rec.modules,
    profile: typeof rec.profile === "string" ? rec.profile : undefined,
  };
}

/**
 * @param {Record<string, string> | null | undefined} payloadMap
 * @param {unknown} input
 */
export function compileWith(payloadMap, input) {
  const src = readInput(input);
  const tierKey = src.tier && Object.prototype.hasOwnProperty.call(TIERS, src.tier) ? src.tier : "core";
  const tierMods = TIERS[/** @type {keyof typeof TIERS} */ (tierKey)];
  const profileKey =
    src.profile && Object.prototype.hasOwnProperty.call(PROFILES, src.profile) ? src.profile : "generic";
  const profile = PROFILES[profileKey] ?? PROFILES.generic;

  const selected = new Set(tierMods);
  selected.add("kernel");
  if (Array.isArray(src.modules)) {
    for (const id of src.modules) {
      if (typeof id !== "string") continue;
      if (!KNOWN.has(id)) continue;
      selected.add(id);
    }
  }

  const map = payloadMap && typeof payloadMap === "object" ? payloadMap : {};
  /** @type {string[]} */
  const parts = [];
  for (const id of ORDER) {
    if (!selected.has(id)) continue;
    const raw = Object.prototype.hasOwnProperty.call(map, id) ? map[id] : undefined;
    if (typeof raw !== "string" || raw.length === 0) continue;
    parts.push(raw);
  }

  const unit = profile.unit;
  let body = parts
    .join("\n\n")
    .split("{{UNIT}}")
    .join(unit)
    .trim();
  if (body.includes("{{")) throw new Error("unsubstituted token");

  if (profile.noun != null) {
    body = body.length > 0 ? `TARGET: ${profile.noun}\n\n${body}` : `TARGET: ${profile.noun}`;
  }
  return body;
}

/**
 * @param {unknown} [input]
 */
export function compile(input) {
  return compileWith(loadPayloads(), input);
}

export function renderThinkcore() {
  const body = compile({ tier: "full", profile: "generic" });
  return (
    "<!-- generated by src/compile.js — do not edit by hand -->\n" +
    "<!-- tier: full | profile: generic | modules: all -->\n" +
    body +
    "\n"
  );
}
